    private void btnRegistrarEstudianteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarEstudianteActionPerformed
String nombre = javax.swing.JOptionPane.showInputDialog(
        this, "Nombre del estudiante:");
if (nombre == null || nombre.trim().isEmpty()) return;

String direccion = javax.swing.JOptionPane.showInputDialog(
        this, "Dirección:");
if (direccion == null) return;

String telefono = javax.swing.JOptionPane.showInputDialog(
        this, "Teléfono:");
if (telefono == null) return;

String fecha = javax.swing.JOptionPane.showInputDialog(
        this, "Fecha de nacimiento:");
if (fecha == null) return;

String codigo = javax.swing.JOptionPane.showInputDialog(
        this, "Código estudiantil:");
if (codigo == null) return;

String programa = javax.swing.JOptionPane.showInputDialog(
        this, "Programa académico:");
if (programa == null) return;

Modelo.Estudiante estudiante =
        new Modelo.Estudiante(
                nombre, direccion, telefono, fecha, codigo, programa);

sistema.registrarEstudiante(estudiante);

javax.swing.JOptionPane.showMessageDialog(
        this, "Estudiante registrado correctamente.");
    }//GEN-LAST:event_btnRegistrarEstudianteActionPerformed

    private void btnRegistrarProfesorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarProfesorActionPerformed
String nombre = javax.swing.JOptionPane.showInputDialog(
        this, "Nombre del profesor:");
if (nombre == null || nombre.trim().isEmpty()) return;

String direccion = javax.swing.JOptionPane.showInputDialog(
        this, "Dirección:");
if (direccion == null) return;

String telefono = javax.swing.JOptionPane.showInputDialog(
        this, "Teléfono:");
if (telefono == null) return;

String fecha = javax.swing.JOptionPane.showInputDialog(
        this, "Fecha de nacimiento:");
if (fecha == null) return;

String cedula = javax.swing.JOptionPane.showInputDialog(
        this, "Cédula:");
if (cedula == null) return;

String area = javax.swing.JOptionPane.showInputDialog(
        this, "Área del profesor:");
if (area == null) return;

try {
    String salarioTexto = javax.swing.JOptionPane.showInputDialog(
            this, "Salario por hora:");
    if (salarioTexto == null) return;

    double salarioHora = Double.parseDouble(salarioTexto);

    String horasTexto = javax.swing.JOptionPane.showInputDialog(
            this, "Horas trabajadas en el mes:");
    if (horasTexto == null) return;

    int horasMes = Integer.parseInt(horasTexto);

    if (salarioHora <= 0 || horasMes <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "El salario y las horas deben ser mayores que cero.");
        return;
    }

    Modelo.Profesor profesor =
            new Modelo.Profesor(
                    nombre, direccion, telefono, fecha,
                    cedula, area, salarioHora, horasMes);

    sistema.registrarProfesor(profesor);

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Profesor registrado correctamente.\n"
            + "Salario total: $" + profesor.calcularSalario()
            + "\nPrestaciones: $" + profesor.calcularPrestaciones());

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Ingresa valores numéricos válidos para salario y horas.");
}
    }//GEN-LAST:event_btnRegistrarProfesorActionPerformed

